create table if not exists public.cashier_observations (
  id bigint generated by default as identity primary key,
  arrival_at timestamptz not null,
  cashier text not null check (cashier in ('K1', 'K2', 'K3', 'K4')),
  q_k1 integer not null default 0 check (q_k1 >= 0),
  q_k2 integer not null default 0 check (q_k2 >= 0),
  q_k3 integer not null default 0 check (q_k3 >= 0),
  q_k4 integer not null default 0 check (q_k4 >= 0),
  service_start_at timestamptz,
  service_finish_at timestamptz,
  note text not null default '',
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint valid_service_times check (
    (service_start_at is null or service_start_at >= arrival_at)
    and (service_finish_at is null or (service_start_at is not null and service_finish_at >= service_start_at))
  )
);

alter table public.cashier_observations enable row level security;

grant select, insert, update, delete on public.cashier_observations to authenticated;
grant usage, select on sequence public.cashier_observations_id_seq to authenticated;

drop policy if exists "Authenticated users can read cashier observations" on public.cashier_observations;
create policy "Authenticated users can read cashier observations"
  on public.cashier_observations for select to authenticated using (true);

drop policy if exists "Authenticated users can insert their observations" on public.cashier_observations;
create policy "Authenticated users can insert their observations"
  on public.cashier_observations for insert to authenticated
  with check (auth.uid() = created_by);

drop policy if exists "Authenticated users can update cashier observations" on public.cashier_observations;
create policy "Authenticated users can update cashier observations"
  on public.cashier_observations for update to authenticated using (true) with check (true);

drop policy if exists "Authenticated users can delete cashier observations" on public.cashier_observations;
create policy "Authenticated users can delete cashier observations"
  on public.cashier_observations for delete to authenticated using (auth.uid() = created_by);

